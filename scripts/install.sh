#!/usr/bin/env bash
# AuditForge — all-in-one installer. Generates every secret the first time, detects the host and
# brings up the whole stack with Docker. Works the same on your PC and on a VPS.
#
# Usage:
#   ./scripts/install.sh                 # host auto-detected (the machine's IP)
#   PUBLIC_HOST=audit.yourdomain.com PUBLIC_SCHEME=https ./scripts/install.sh   # VPS
#
# Safe to re-run: if deploy/.env already exists it does NOT rotate keys; it only rebuilds and
# brings things up. To start from scratch, delete deploy/.env and the data volume.
set -euo pipefail

cd "$(dirname "$0")/.."
DEPLOY_DIR="deploy"
ENV_FILE="$DEPLOY_DIR/.env"

# ---- checks ----
command -v docker >/dev/null 2>&1 || { echo "Docker is missing. Install it: https://docs.docker.com/get-docker/"; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "The 'docker compose' (v2) plugin is missing."; exit 1; }
command -v openssl >/dev/null 2>&1 || { echo "openssl is missing."; exit 1; }

compose() { docker compose -f "$DEPLOY_DIR/docker-compose.yml" --env-file "$ENV_FILE" "$@"; }

b64url() { openssl enc -base64 -A | tr '+/' '-_' | tr -d '='; }
gen_jwt() { # $1 = JSON payload ; uses $JWT_SECRET
  local header payload sig
  header=$(printf '%s' '{"alg":"HS256","typ":"JWT"}' | b64url)
  payload=$(printf '%s' "$1" | b64url)
  sig=$(printf '%s' "${header}.${payload}" | openssl dgst -binary -sha256 -hmac "$JWT_SECRET" | b64url)
  printf '%s' "${header}.${payload}.${sig}"
}
pem1line() { awk 'BEGIN{ORS="\\n"} {print}' "$1"; } # PEM to one line with literal \n

# ---- public host ----
PUBLIC_SCHEME="${PUBLIC_SCHEME:-http}"
GATEWAY_PORT="${GATEWAY_PORT:-8000}"
WEB_PORT="${WEB_PORT:-3000}"
MAIL_UI_PORT="${MAIL_UI_PORT:-8025}"
if [ -z "${PUBLIC_HOST:-}" ]; then
  PUBLIC_HOST=$(ip route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')
  [ -z "$PUBLIC_HOST" ] && PUBLIC_HOST=$(hostname -I 2>/dev/null | awk '{print $1}')
  [ -z "$PUBLIC_HOST" ] && PUBLIC_HOST="localhost"
fi
SUPABASE_PUBLIC_URL="${PUBLIC_SCHEME}://${PUBLIC_HOST}:${GATEWAY_PORT}"
SITE_URL="${PUBLIC_SCHEME}://${PUBLIC_HOST}:${WEB_PORT}"

if [ -f "$ENV_FILE" ]; then
  echo "==> $ENV_FILE already exists: reusing secrets. (Delete the file to regenerate them.)"
else
  echo "==> Generating secrets into $ENV_FILE…"
  JWT_SECRET=$(openssl rand -base64 30)
  IAT=$(date +%s); EXP=$((IAT + 5*365*24*3600))
  ANON_KEY=$(gen_jwt "{\"role\":\"anon\",\"iss\":\"supabase\",\"iat\":$IAT,\"exp\":$EXP}")
  SERVICE_ROLE_KEY=$(gen_jwt "{\"role\":\"service_role\",\"iss\":\"supabase\",\"iat\":$IAT,\"exp\":$EXP}")
  POSTGRES_PASSWORD=$(openssl rand -hex 16)
  WORKER_DB_PASSWORD=$(openssl rand -hex 16)
  SETTINGS_ENCRYPTION_KEY=$(openssl rand -base64 32)

  TMPK=$(mktemp -d)
  openssl genpkey -algorithm ed25519 -out "$TMPK/priv.pem" 2>/dev/null
  openssl pkey -in "$TMPK/priv.pem" -pubout -out "$TMPK/pub.pem" 2>/dev/null
  SCOPE_TOKEN_PRIVATE_KEY=$(pem1line "$TMPK/priv.pem")
  SCOPE_TOKEN_PUBLIC_KEY=$(pem1line "$TMPK/pub.pem")
  rm -rf "$TMPK"

  umask 077
  cat > "$ENV_FILE" <<EOF
# AuditForge — generated by install.sh. Do NOT commit or share it.
PUBLIC_HOST=$PUBLIC_HOST
PUBLIC_SCHEME=$PUBLIC_SCHEME
GATEWAY_PORT=$GATEWAY_PORT
WEB_PORT=$WEB_PORT
MAIL_UI_PORT=$MAIL_UI_PORT
SUPABASE_PUBLIC_URL=$SUPABASE_PUBLIC_URL
SITE_URL=$SITE_URL

POSTGRES_DB=postgres
POSTGRES_PORT=5432
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
JWT_SECRET=$JWT_SECRET
JWT_EXPIRY=3600
ANON_KEY=$ANON_KEY
SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
DISABLE_SIGNUP=true
MAILER_AUTOCONFIRM=false

SETTINGS_ENCRYPTION_KEY=$SETTINGS_ENCRYPTION_KEY
SCOPE_TOKEN_PRIVATE_KEY=$SCOPE_TOKEN_PRIVATE_KEY
SCOPE_TOKEN_PUBLIC_KEY=$SCOPE_TOKEN_PUBLIC_KEY
WORKER_DB_PASSWORD=$WORKER_DB_PASSWORD
AUDITFORGE_SCAN_DISPATCH=queue

# Optional Claude-BugHunter integration. Pin a REVIEWED commit to install it.
PACK_COMMIT=
ENGAGEMENT_CMD=
EOF
fi

echo "==> Building and starting (this can take a while the first time)…"
compose up -d --build

echo
echo "==================== AuditForge is up ===================="
echo "Panel:            $SITE_URL"
echo "Mailbox (Mailpit): ${PUBLIC_SCHEME}://${PUBLIC_HOST}:${MAIL_UI_PORT}"
echo
echo "First login: there is no public sign-up. Create your user with:"
echo "  ./scripts/create-user.sh you@example.com"
echo "Then open the panel, request the magic link and open it from the mailbox (Mailpit)."
echo
echo "Operate: compose from $DEPLOY_DIR  (docker compose logs -f | down | up -d)"
echo "=========================================================="
